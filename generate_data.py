def load_schema():
    with open(SCHEMA_PATH, encoding="utf-8") as f:
        return json.load(f)


def render(template, rng):
    slots = {}

    def repl(m):
        key = m.group(1)
        entry = rng.choice(SLOT_VALUES[key])
        if isinstance(entry, str):
            canonical, surfaces = entry, [entry]
        else:
            canonical, surfaces = entry
        slots[key] = canonical          # 标签用归一化标准值
        return rng.choice(surfaces)     # 句子用口语/书面变体

    text = re.sub(r"\{([^{}]+)\}", repl, template)
    return text, slots


def make_messages(system_prompt, utterance, intent, slots):
    assistant = json.dumps(
        {"intent": intent, "slots": slots}, ensure_ascii=False, separators=(",", ":")
    )
    return {
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": utterance},
            {"role": "assistant", "content": assistant},
        ]
    }


def sample_intent(intent, rng):
    """为一个意图生成 (utterance, slots) 列表"""
    out = []
    seen = set()
    max_guard = PER_INTENT_TOTAL * 30

    if intent in ZERO_SLOT_POOLS:
        base_list = ZERO_SLOT_POOLS[intent]
        guard = 0
        while len(out) < PER_INTENT_TOTAL and guard < max_guard:
            guard += 1
            base = rng.choice(base_list)
            prefix = rng.choice(PREFIXES)
            suffix = rng.choice(SUFFIXES)
            ut = (prefix + base + suffix).strip()
            if ut in seen:
                continue
            seen.add(ut)
            out.append((ut, {}))
    else:
        templates = INTENT_TEMPLATES[intent]
        guard = 0
        while len(out) < PER_INTENT_TOTAL and guard < max_guard:
            guard += 1
            tpl = rng.choice(templates)
            text, slots = render(tpl, rng)
            prefix = rng.choice(PREFIXES)
            suffix = rng.choice(SUFFIXES)
            ut = (prefix + text + suffix).strip()
            if ut in seen:
                continue
            seen.add(ut)
            out.append((ut, slots))

    if len(out) < PER_INTENT_TOTAL:
        print(f"[警告] {intent} 仅生成 {len(out)} 条唯一样本")
    return out


def main():
    random.seed(SEED)
    schema = load_schema()
    system_prompt = schema["system_prompt"]
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    train_lines, test_lines, review_lines = [], [], []
    stats = {}

    for intent in schema["intents"]:
        samples = sample_intent(intent, random)
        random.shuffle(samples)
        test = samples[:TEST_PER_INTENT]
        train = samples[TEST_PER_INTENT:]
        stats[intent] = {"train": len(train), "test": len(test)}

        for ut, slots in train:
            train_lines.append(make_messages(system_prompt, ut, intent, slots))
        for ut, slots in test:
            test_lines.append(make_messages(system_prompt, ut, intent, slots))
        for ut, slots in test[:REVIEW_PER_INTENT]:
            review_lines.append({"utterance": ut, "intent": intent, "slots": slots})

    # 注入手写真实口语语料（全部进训练集）
    real_count = 0
    for intent, ut, slots in REAL_CORPUS:
        train_lines.append(make_messages(system_prompt, ut, intent, slots))
        real_count += 1
    print(f"已注入手写真实语料 {real_count} 条")

    random.shuffle(train_lines)
    random.shuffle(test_lines)

    paths = {
        "train.jsonl": train_lines,
        "test.jsonl": test_lines,
        "review_samples.jsonl": review_lines,
    }
    for name, lines in paths.items():
        path = os.path.join(OUTPUT_DIR, name)
        with open(path, "w", encoding="utf-8") as f:
            for line in lines:
                f.write(json.dumps(line, ensure_ascii=False) + "\n")
        print(f"已写出 {path}（{len(lines)} 条）")

    print("\n每类分布（训练集=模板+语料）：")
    for intent, s in stats.items():
        print(f"  {intent}: train={s['train']} test={s['test']}")


if __name__ == "__main__":
    main()